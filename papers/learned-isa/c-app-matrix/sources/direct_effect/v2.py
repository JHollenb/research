MASK64 = P.MASK64
FORMS = dict(P.FORMS)
FORMS.update({"mov_r32_c7": (32, "mov", 4), "mov_r64_r64": (64, "mov", 0), "mov_r32_r32": (32, "mov", 0),
              "mov_r64_rm": (64, "mov", 0), "xor_r64_r64": (64, "xor", 0), "store_m64_r64": (64, "store", 0)})
FORM_NAMES = tuple(FORMS)
HELDOUT_PAIRS = set(P.HELDOUT_PAIRS) | {("mov_r64_r64", 3), ("mov_r32_c7", 5)}
_hb = random.Random(20261014)
HELD_BYTES = tuple(sorted(_hb.sample([b for b in range(256) if b not in (0, 1, 8, 60)], 24)))
ARITH = {"add", "sub", "cmp", "inc", "dec"}


def encode(form, reg=0, imm=0, src=0):
    if form in P.FORMS:
        return P.encode(form, reg, imm, src)
    width = FORMS[form][0]
    if form == "mov_r32_c7":
        code, operand, dest = bytes([0xC7, 0xC0 + reg]) + (imm & 0xFFFFFFFF).to_bytes(4, "little"), imm & 0xFFFFFFFF, reg
    elif form == "mov_r64_r64":
        code, operand, dest = bytes([0x48, 0x89, 0xC0 | (src << 3) | reg]), 0, reg
    elif form == "mov_r32_r32":
        code, operand, dest = bytes([0x89, 0xC0 | (src << 3) | reg]), 0, reg
    elif form == "mov_r64_rm":
        code, operand, dest = bytes([0x48, 0x8B, 0xC0 | (reg << 3) | src]), 0, reg
    elif form == "xor_r64_r64":
        code, operand, dest = bytes([0x48, 0x31, 0xC0 | (src << 3) | reg]), 0, reg
    elif form == "store_m64_r64":
        code, operand, dest = bytes([0x48, 0x89, 0x04 | (src << 3), 0x24]), 0, 4
    else:
        raise ValueError(form)
    return P.Instruction(form, code, dest, src, width, operand)


def extra_holdout_pairs(n, seed=20261015):
    """Round-4 coverage scan: n more (form, register) pairs withheld from training, nested (the 7 are inside the 21).
    Drawn from the forms whose destination register is encoded in the instruction (not AL-only, nop, store or syscall)."""
    pool = sorted((f, r) for f in FORM_NAMES if f not in P.AL8 and f not in ("nop", "syscall", "store_m64_r64")
                  for r in range(8) if (f, r) not in HELDOUT_PAIRS)
    return sorted(random.Random(seed).sample(pool, 21)[:n])


# Training-data mix (round 3 can raise both): fraction of full-width random immediates in ≥4-byte forms, and how
# much more often wide-immediate forms are drawn. Panels always use the defaults.
MIX = {"wide_large": 0.55, "wide_boost": 1}
WIDE_FORMS = tuple(f for f in FORMS if FORMS[f][2] >= 4)


def raw_imm(rng, nbytes, mode, mix=None):
    if nbytes == 0:
        return 0
    mix = mix or {}
    r = rng.random()
    large = mix.get("wide_large", 0.55) if nbytes >= 4 else 0.55
    small = 0.3 * (1 - large) / 0.45  # keep the byte : special ratio of v2 (0.30 : 0.15)
    value = rng.randrange(256) if r < small else (P.special_value(rng) & ((1 << 8 * nbytes) - 1) if r < 1 - large
                                                  else rng.getrandbits(8 * nbytes))
    low = value & 0xFF
    if mode == "train" and low in HELD_BYTES:
        value = (value & ~0xFF) | rng.choice([b for b in range(256) if b not in HELD_BYTES])
    if mode == "held":
        value = (value & ~0xFF) | rng.choice(HELD_BYTES)
    return value


def random_instruction(rng, mode="train", forms=FORM_NAMES, pairs="exclude", mix=None):
    if mix and mix.get("wide_boost", 1) > 1:
        forms = tuple(forms) + tuple(f for f in forms if f in WIDE_FORMS) * (mix["wide_boost"] - 1)
    while True:
        form = rng.choice(forms)
        reg = 0 if form in P.AL8 else rng.randrange(8)
        src = rng.randrange(8)
        held = (form, reg) in HELDOUT_PAIRS
        if pairs == "exclude" and held or pairs == "only" and not held:
            continue
        if mix and pairs == "exclude" and [form, reg] in mix.get("exclude_pairs", ()):
            continue  # round-4 coverage scan: extra [form, reg] pairs withheld from training and feedback
        if pairs == "extra" and [form, reg] not in (mix or {}).get("exclude_pairs", ()):
            continue
        if mode == "held" and FORMS[form][2] == 0:
            continue
        return encode(form, reg, raw_imm(rng, FORMS[form][2], mode, mix), src)


class Emulator:
    """Unicorn on the 8-GPR + 4-flag state, with an optional mapped stack page for stores."""

    def __init__(self):
        import unicorn
        from unicorn import x86_const as x
        self.u, self.x = unicorn, x
        self.regs = [getattr(x, f"UC_X86_REG_{n}") for n in P.GPRS]

    def step(self, state, code):
        u, x = self.u, self.x
        uc = u.Uc(u.UC_ARCH_X86, u.UC_MODE_64)
        uc.mem_map(P.CODE_BASE, 0x2000)
        uc.mem_write(P.CODE_BASE, code[:P.WINDOW] + b"\x90" * 16)
        rsp = state["regs"][4]
        page = rsp & ~0xFFF
        mapped_stack = P.CODE_BASE + 0x2000 <= page < MASK64 - 0x3000 and not (P.CODE_BASE - 0x3000 <= page < P.CODE_BASE + 0x2000)
        if mapped_stack:
            uc.mem_map(page, 0x2000)
        for reg, value in zip(self.regs, state["regs"], strict=True):
            uc.reg_write(reg, value)
        uc.reg_write(x.UC_X86_REG_EFLAGS, 2 | sum(v << P.FLAG_BITS[f] for f, v in state["flags"].items()))
        uc.emu_start(P.CODE_BASE, P.CODE_BASE + 0x1000, count=1)
        eflags = uc.reg_read(x.UC_X86_REG_EFLAGS)
        after = {"regs": [uc.reg_read(r) & MASK64 for r in self.regs],
                 "flags": {f: (eflags >> b) & 1 for f, b in P.FLAG_BITS.items()},
                 "rip": state["rip"] + uc.reg_read(x.UC_X86_REG_RIP) - P.CODE_BASE}
        stored = int.from_bytes(bytes(uc.mem_read(rsp, 8)), "little") if mapped_stack else None
        return after, stored


def make_example(rng, emu, ins, state=None):
    state = state or P.random_state(rng)
    if ins.form == "store_m64_r64":
        state["regs"][4] = 0x7FF000000000 + rng.randrange(0, 1 << 33) * 8
    win = ins.code + bytes(rng.randrange(256) for _ in range(P.WINDOW - len(ins.code)))
    if ins.form == "syscall":
        after, stored = {"regs": list(state["regs"]), "flags": dict(state["flags"]), "rip": state["rip"] + 2}, None
    else:
        after, stored = emu.step(dict(state, rip=P.CODE_BASE), ins.code)
        after["rip"] = state["rip"] + (after["rip"] - P.CODE_BASE)
    store = ins.form == "store_m64_r64"
    if store and stored != state["regs"][ins.src]:
        raise ValueError("store instrument mismatch")
    return {"form": FORM_NAMES.index(ins.form), "window": win, "before": state, "after": after, "length": len(ins.code),
            "dest": ins.dest, "src": ins.src, "width": ins.width, "imm": ins.imm, "syscall": int(ins.form == "syscall"),
            "store": int(store), "store_addr": state["regs"][4] if store else 0, "store_value": stored if store else 0}


def pack(examples):
    u = lambda vals: np.array(vals, dtype=np.uint64).view(np.int64)
    return {"form": np.array([e["form"] for e in examples], np.int16),
            "window": np.frombuffer(b"".join(e["window"] for e in examples), np.uint8).reshape(-1, P.WINDOW).copy(),
            "regs": u([e["before"]["regs"] for e in examples]), "after": u([e["after"]["regs"] for e in examples]),
            "flags": np.array([[e["before"]["flags"][f] for f in FLAG_ORDER] for e in examples], np.uint8),
            "after_flags": np.array([[e["after"]["flags"][f] for f in FLAG_ORDER] for e in examples], np.uint8),
            "length": np.array([e["length"] for e in examples], np.int16), "dest": np.array([e["dest"] for e in examples], np.int16),
            "src": np.array([e["src"] for e in examples], np.int16),
            "width": np.array([P.WIDTH_CLASS[e["width"]] for e in examples], np.int16),
            "imm": u([e["imm"] for e in examples]), "syscall": np.array([e["syscall"] for e in examples], np.uint8),
            "store": np.array([e["store"] for e in examples], np.uint8),
            "store_addr": u([e["store_addr"] for e in examples]), "store_value": u([e["store_value"] for e in examples])}


def _chunk(args):
    n, seed, mode, pairs, mix = args
    rng, emu = random.Random(seed), Emulator()
    return pack([make_example(rng, emu, random_instruction(rng, mode, pairs=pairs, mix=mix)) for _ in range(n)])


def generate(n, seed, mode="train", pairs="exclude", workers=4, mix=None):
    import multiprocessing as mp
    per = math.ceil(n / workers)
    jobs = [(min(per, n - i * per), seed * 1000 + i, mode, pairs, mix) for i in range(workers) if n - i * per > 0]
    if workers > 1:
        with mp.get_context("fork").Pool(workers) as pool:
            parts = pool.map(_chunk, jobs)
    else:
        parts = [_chunk(j) for j in jobs]
    return {k: np.concatenate([p[k] for p in parts]) for k in parts[0]}


