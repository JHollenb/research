@torch.no_grad()
def step(model, code, state, memory, device):
    off = state["rip"] - P.CODE_BASE
    window = code[off:off + P.WINDOW].ljust(P.WINDOW, b"\0")
    win = torch.tensor([[(b >> j) & 1 for b in window for j in range(8)]], dtype=torch.float32, device=device)
    regs = bits64(torch.tensor(np.array([state["regs"]], dtype=np.uint64).view(np.int64), device=device))
    flags = torch.tensor([[state["flags"][f] for f in FLAG_ORDER]], dtype=torch.float32, device=device)
    out = model(win, regs, flags)
    hard = lambda k: (out[k][0] > 0).long().tolist()
    from_bits = lambda bits: sum(int(b) << i for i, b in enumerate(bits))
    nxt = {"regs": [from_bits(hard("regs")[r]) for r in range(8)],
           "flags": {f: int(out["flags"][0, k] > 0) for k, f in enumerate(FLAG_ORDER)},
           "rip": state["rip"] + int(out["length"][0].argmax()) + 1}
    if float(out["store"][0]) > 0:
        addr, value = from_bits(hard("store_addr")), from_bits(hard("store_value"))
        for i in range(8):
            memory[(addr + i) & MASK64] = (value >> (8 * i)) & 0xFF
    return nxt, bool(float(out["syscall"][0]) > 0)


def os_boundary(state, memory, stdout):
    """Linux write/exit after the model emits SYSCALL. Kernel effects: RAX = result, RCX = return RIP."""
    rax, rdi, rsi, rdx = state["regs"][0], state["regs"][7], state["regs"][6], state["regs"][2]
    if rax == 60:
        return "exit", rdi & 0xFF
    if rax == 1 and rdi == 1 and rdx < 4096:
        data = [memory.get((rsi + i) & MASK64) for i in range(rdx)]
        if any(b is None for b in data):
            return "fault", None
        stdout.extend(data)
        state["regs"][0] = rdx
        state["regs"][1] = state["rip"]
        return "running", None
    return "unsupported_syscall", None


def run_program(model, code, initial, max_steps, device, native=None):
    state = {"regs": list(initial["regs"]), "flags": dict(initial["flags"]), "rip": initial["rip"]}
    memory, stdout, traj = {}, bytearray(), [state]
    first, agree, status, exit_code = None, 1, "running", None
    for i in range(max_steps):
        nxt, sc = step(model, code, state, memory, device)
        if sc:
            nxt = {"regs": list(state["regs"]), "flags": dict(state["flags"]), "rip": state["rip"] + 2}
            status, exit_code = os_boundary(nxt, memory, stdout)
            if status != "running":
                break
        state = nxt
        traj.append(state)
        if native is not None:
            ref = native[i + 1] if i + 1 < len(native) else None
            ok = ref is not None and ref["rip"] == state["rip"] and ref["regs"] == state["regs"] and ref["flags"] == state["flags"]
            agree += ok
            if not ok and first is None:
                first = i
    return {"steps": len(traj) - 1, "status": status, "exit_code": exit_code, "stdout": bytes(stdout).hex(),
            "first_divergence_vs_native": first, "native_agree": agree,
            "native_steps": len(native) if native is not None else None}


def stdout_code(n):
    inc = n - 11
    return (bytes.fromhex("31c0") + bytes.fromhex("4883c001") * inc
            + bytes.fromhex("4883ec0848890424bf010000004889e6ba08000000b8010000000f0531ffb83c0000000f05")), inc


def field_starts(model, d, chunk=256):
    """fieldptr models: argmax start bit of the destination and source field pointers, histogrammed per form."""
    from collections import Counter
    model.eval()
    hist = {}
    n = d["form"].shape[0]
    with torch.no_grad():
        for start in range(0, n, chunk):
            idx = torch.arange(start, min(n, start + chunk), device=d["form"].device)
            t = batch(d, idx)
            cap = {}
            model(t["win"], t["regs"], t["flags"], capture=cap)
            first = cap.get("field_start1", cap["field_start"]).tolist()
            for f, j, j1 in zip(t["form"].tolist(), cap["field_start"].tolist(), first, strict=True):
                h = hist.setdefault(FORM_NAMES[f], {"dest": Counter(), "src": Counter(), "dest_pass1": Counter(),
                                                    "src_pass1": Counter(), "agree": Counter()})
                h["dest"][j[0]] += 1
                h["src"][j[1]] += 1
                h["dest_pass1"][j1[0]] += 1
                h["src_pass1"][j1[1]] += 1
                h["agree"]["dest"] += j[0] == j1[0]
                h["agree"]["src"] += j[1] == j1[1]
                h["agree"]["rows"] += 1
    return {f: {k: dict(v.most_common(4)) if k != "agree" else dict(v) for k, v in h.items()} for f, h in hist.items()}


def program_panel(model, device, seed, lengths=(16, 128, 1024), counts=(16, 8, 4), mode="train", pairs="exclude", mix=None,
                  grid=None, split="train"):
    rng, emu = random.Random(seed), Emulator()
    forms = tuple(f for f in FORM_NAMES if f not in ("syscall", "store_m64_r64"))
    out = {}
    for length, count in zip(lengths, counts, strict=True):
        firsts = []
        for _ in range(count):
            if grid is not None:  # factor-grid splits (direct_effect.grid)
                from direct_effect import grid as G
                code = b"".join(G.random_instruction(rng, grid, split, mode, forms=forms).code for _ in range(length))
            else:
                code = b"".join(random_instruction(rng, mode, forms, pairs, mix).code for _ in range(length))
            state = P.random_state(rng)
            ref, cur = [state], state
            for _ in range(length):
                off = cur["rip"] - P.CODE_BASE
                cur, _ = emu.step(dict(cur, rip=P.CODE_BASE), code[off:off + P.WINDOW])
                cur["rip"] = ref[-1]["rip"] + cur["rip"] - P.CODE_BASE
                ref.append(cur)
            r = run_program(model, code, state, length, device, ref)
            firsts.append(r["first_divergence_vs_native"] if r["steps"] == length else (r["first_divergence_vs_native"] or r["steps"]))
        out[str(length)] = {"programs": count, "exact": sum(f is None for f in firsts), "first_divergence": firsts}
    return out


