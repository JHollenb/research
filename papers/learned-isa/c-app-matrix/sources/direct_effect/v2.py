SHIFTS = {}


def bits64(x):
    s = SHIFTS.setdefault(x.device, torch.arange(64, device=x.device))
    return ((x.unsqueeze(-1) >> s) & 1).float()


def batch(d, idx):
    b = {k: v[idx] for k, v in d.items()}
    win = ((b["window"].long().unsqueeze(-1) >> torch.arange(8, device=idx.device)) & 1).flatten(1).float()
    return {"win": win, "regs": bits64(b["regs"]), "flags": b["flags"].float(), "after": bits64(b["after"]),
            "after_flags": b["after_flags"].float(), "length": b["length"].long() - 1, "dest": b["dest"].long(),
            "src": b["src"].long(), "width": b["width"].long(), "imm": bits64(b["imm"]), "syscall": b["syscall"].float(),
            "store": b["store"].float(), "store_addr": bits64(b["store_addr"]), "store_value": bits64(b["store_value"]),
            "form": b["form"].long()}


def loss_fn(out, t):
    changed = (t["after"] != t["regs"]).float()
    m = t["store"].unsqueeze(-1)
    terms = [F.binary_cross_entropy_with_logits(out["regs"], t["after"], weight=1 + 20 * changed),
             F.binary_cross_entropy_with_logits(out["flags"], t["after_flags"]),
             F.cross_entropy(out["dest"], t["dest"]), F.cross_entropy(out["src"], t["src"]),
             F.cross_entropy(out["width"], t["width"]), F.cross_entropy(out["length"], t["length"]),
             F.binary_cross_entropy_with_logits(out["syscall"], t["syscall"]),
             F.binary_cross_entropy_with_logits(out["imm"], t["imm"]),
             F.binary_cross_entropy_with_logits(out["store"], t["store"])]
    if m.sum() > 0:
        terms.append((F.binary_cross_entropy_with_logits(out["store_addr"], t["store_addr"], reduction="none") * m).sum() / (m.sum() * 64))
        terms.append((F.binary_cross_entropy_with_logits(out["store_value"], t["store_value"], reduction="none") * m).sum() / (m.sum() * 64))
    if "field_start_p" in out and FORM_INVARIANCE["weight"]:
        terms.append(FORM_INVARIANCE["weight"] * form_invariance(out["field_start_p"], t["form"]))
    return sum(terms)


# Round 6 (combined arm): supplied prior "a field's location depends only on the form". The generator's form id is
# used in the training loss only (never at inference) to penalize within-form spread of the field-start
# distributions, which gives gradient pressure toward register-independent starts without revealing where fields are.
FORM_INVARIANCE = {"weight": 0.0}


def form_invariance(p, forms):
    """p [passes,B,2,J] start distributions; mean over rows of sum_j (p - mean_of_its_form)^2."""
    flat = p.permute(1, 0, 2, 3).flatten(1)  # [B, passes*2*J]
    onehot = F.one_hot(forms, len(FORM_NAMES)).float()  # [B,F]
    mean = (onehot.T @ flat) / onehot.sum(0).clamp(min=1).unsqueeze(1)  # [F, D]
    return ((flat - mean[forms]) ** 2).sum(1).mean()


@torch.no_grad()
def exactness(model, d, chunk=256, rows=False):
    """Vectorized isolated exactness: full state, fields, per form; wide_large = ≥4-byte immediates ≥ 256."""
    model.eval()
    n = d["form"].shape[0]
    keys = ("state", "regs", "dest_value", "flags", "CF", "OF", "length", "dest_decode", "imm_decode", "store", "dest_pick")
    acc = {k: torch.zeros(n, dtype=torch.bool, device=d["form"].device) for k in keys}
    imm_forms = torch.tensor([FORMS[f][2] > 0 for f in FORM_NAMES], device=d["form"].device)
    for start in range(0, n, chunk):
        idx = torch.arange(start, min(n, start + chunk), device=d["form"].device)
        t = batch(d, idx)
        out = model(t["win"], t["regs"], t["flags"])
        regs = ((out["regs"] > 0).float() == t["after"]).all(-1)
        fl = (out["flags"] > 0).float() == t["after_flags"]
        length = out["length"].argmax(-1) == t["length"]
        sc = ((out["syscall"] > 0).float() == t["syscall"])
        st = ((out["store"] > 0).float() == t["store"])
        st_vals = ((out["store_addr"] > 0).float() == t["store_addr"]).all(-1) & ((out["store_value"] > 0).float() == t["store_value"]).all(-1)
        st = st & (st_vals | (t["store"] == 0))
        dv = regs.gather(1, t["dest"].clamp(0, 7).unsqueeze(1)).squeeze(1)
        imm_ok = ((out["imm"] > 0).float() == t["imm"]).all(-1) | ~imm_forms[t["form"]]
        acc["state"][idx] = regs.all(-1) & fl.all(-1) & length & sc & st
        acc["regs"][idx] = regs.all(-1)
        acc["dest_value"][idx] = dv
        acc["flags"][idx] = fl.all(-1)
        acc["CF"][idx], acc["OF"][idx] = fl[:, 0], fl[:, 3]
        acc["length"][idx] = length
        acc["dest_decode"][idx] = out["dest"].argmax(-1) == t["dest"]
        acc["dest_pick"][idx] = out.get("reg_pick", out["dest"]).argmax(-1) == t["dest"]
        acc["imm_decode"][idx] = imm_ok
        acc["store"][idx] = st
    forms = d["form"].long()
    per_form = {}
    for i, f in enumerate(FORM_NAMES):
        m = forms == i
        if m.any():
            per_form[f] = round(float(acc["state"][m].float().mean()), 4)
    res = {k: float(v.float().mean()) for k, v in acc.items()}
    res["n"] = n
    res["per_form_state"] = per_form
    res["per_form_dest_pick"] = {f: round(float(acc["dest_pick"][forms == i].float().mean()), 4)
                                 for i, f in enumerate(FORM_NAMES) if (forms == i).any()}
    pair_key = forms * 8 + d["dest"].long().clamp(0, 7)
    res["per_pair_counts"] = {f"{FORM_NAMES[int(k) // 8]}:{int(k) % 8}": [int(acc["state"][pair_key == k].sum()), int((pair_key == k).sum()),
                                                                     int(acc["dest_pick"][pair_key == k].sum())]
                              for k in pair_key.unique()}  # [exact, rows, dest-pick correct]
    groups = {"al8": [], "32-bit": [], "64-bit": []}
    for f, v in per_form.items():
        groups["al8" if f in P.AL8 else ("32-bit" if FORMS[f][0] == 32 else "64-bit")].append(v)
    res["per_width_state"] = {k: round(sum(v) / len(v), 4) if v else None for k, v in groups.items()}
    wide = torch.tensor([FORMS[f][2] >= 4 for f in FORM_NAMES], device=forms.device)[forms]
    large = wide & ((d["imm"] < 0) | (d["imm"] >= 256))
    res["wide_large_state"] = float(acc["state"][large].float().mean()) if large.any() else None
    res["wide_large_n"] = int(large.sum())
    res["wide_small_state"] = float(acc["state"][wide & ~large].float().mean()) if (wide & ~large).any() else None
    if rows:
        res["rows"] = {k: acc[k].cpu().tolist() for k in ("state", "flags")}
    return res


