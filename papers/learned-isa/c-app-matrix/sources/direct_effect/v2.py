def carry_in(kind, a, b, width):
    sub = kind in ("sub", "cmp", "dec")
    c, out = 0, []
    for i in range(width):
        out.append(c)
        ai, bi = (a >> i) & 1, (b >> i) & 1
        c = ((1 - ai) & bi) | ((1 - (ai ^ bi)) & c) if sub else (ai & bi) | (c & (ai ^ bi))
    return out


@torch.no_grad()
def probe_panel(model, panel, device, max_rows=1500):
    """Linear probes at the input token and last mixer layer: carry-in, immediate bit, destination-operand bit."""
    n = min(max_rows, panel["form"].shape[0])
    idx = torch.arange(n, device=device)
    t = batch(panel, idx)
    cap = {}
    model.eval()
    for s in range(0, n, 256):
        part = {}
        j = idx[s:s + 256]
        tt = batch(panel, j)
        model(tt["win"], tt["regs"], tt["flags"], capture=part)
        for k in ["input"] + [f"layer{i}" for i in range(len(model.mixers))]:
            cap.setdefault(k, []).append(part[k].cpu())
    cap = {k: torch.cat(v).numpy() for k, v in cap.items()}
    forms = panel["form"][:n].cpu().numpy()
    regs = panel["regs"][:n].cpu().numpy().view(np.uint64)
    imms = panel["imm"][:n].cpu().numpy().view(np.uint64)
    dests = panel["dest"][:n].cpu().numpy()
    rows = {"carry_in": [], "imm_bit": [], "dest_bit": [], "wide_imm_bit": []}
    for j in range(n):
        f = FORM_NAMES[forms[j]]
        width, kind, nimm = FORMS[f]
        a = int(regs[j, dests[j]]) if 0 <= dests[j] < 8 else 0
        if kind in ARITH:
            b = 1 if kind in ("inc", "dec") else int(imms[j])
            for i, v in enumerate(carry_in(kind, a, b, width)):
                rows["carry_in"].append((j, i, v))
        if nimm:
            for i in range(min(64, width)):
                rows["imm_bit"].append((j, i, (int(imms[j]) >> i) & 1))
        if nimm >= 4 and int(imms[j]) >= 256:  # the wide copy: bits above the low byte of a large immediate
            for i in range(8, min(64, 8 * nimm)):
                rows["wide_imm_bit"].append((j, i, (int(imms[j]) >> i) & 1))
        if kind in ARITH | {"mov", "xor", "and", "or", "test"} and f not in ("store_m64_r64",):
            for i in range(0, width, 4):
                rows["dest_bit"].append((j, i, (a >> i) & 1))
    out = {}
    for target, rr in rows.items():
        rr = np.array(rr)
        if len(rr) < 50:
            continue
        split = (rr[:, 0] % 2) == 0
        y = rr[:, 2]
        out[target] = {"majority": float(max(y[~split].mean(), 1 - y[~split].mean())), "positions": int(len(rr))}
        for layer, h in cap.items():
            X = h[rr[:, 0], rr[:, 1]]
            if len(set(y[split])) < 2:
                continue
            acc, bal = logistic_probe(X[split], y[split], X[~split], y[~split])
            out[target][layer] = bal
    return out


# ---------------------------------------------------------------- training


def lr_at(update, base, warmup, total, floor=0.1):
    if update < warmup:
        return base * (update + 1) / warmup
    p = min(1.0, (update - warmup) / max(1, total - warmup))
    return base * (floor + (1 - floor) * 0.5 * (1 + math.cos(math.pi * p)))


def saturn_module():
    """Saturn checkpoint controller; ISA_SATURN_CONTROLLER points at a specific revision (else the sealed/vendored one)."""
    import importlib.util
    import os
    import sys
    path = os.environ.get("ISA_SATURN_CONTROLLER")
    if not path:
        from isa_lab.dependencies import saturn_controller
        return saturn_controller()
    name = "_isa_saturn_controller_override"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(name, path)
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return sys.modules[name]


def train(arch, cfg, out, device, emit=print, data=None):
    FORM_INVARIANCE["weight"] = float(cfg.get("form_invariance", 0.0))
    out = Path(out)
    (out / "futures").mkdir(parents=True, exist_ok=True)
    torch.manual_seed(cfg["seed"])
    t0 = time.perf_counter()
    d, fb, probe = data
    model = Executor(arch, store=True, aligned=cfg.get("aligned", False), relptr=cfg.get("relptr", False),
                     regptr=cfg.get("regptr", False), fieldptr=cfg.get("fieldptr", False), maskkey=cfg.get("maskkey", False), aux_detach=cfg.get("aux_detach")).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=cfg["lr"], weight_decay=1e-4)
    saturn = saturn_module()
    k = cfg.get("margin_se", 0.0)
    schedule_on = cfg.get("schedule_on", "accepted")  # "attempts": cosine follows attempted updates, so it always finishes
    cursor = {"updates": 0}
    attempt = {"interval": -1, "step": 0}
    observations = []
    total, warmup = cfg["max_updates"], cfg["warmup"]
    n = d["form"].shape[0]
    if k > 0:  # noise-aware promotion: paired per-row SE on the fixed feedback panel and rollout programs
        noise = lambda key: {"standard_errors": k, "paired_evidence": key}  # noqa: E731
        policy = saturn.PromotionPolicy("lexicographic", (
            saturn.PromotionObjective("validation", "feedback_state", "maximize", **noise("state_rows")),
            saturn.PromotionObjective("autonomous_rollout", "rollout", "maximize", **noise("rollout_rows")),
            saturn.PromotionObjective("trace_endpoints", "feedback_flags", "maximize", **noise("flag_rows"))),
            promote_equivalent=True)
    else:
        policy = saturn.PromotionPolicy("lexicographic", (
            saturn.PromotionObjective("validation", "feedback_state", "maximize"),
            saturn.PromotionObjective("autonomous_rollout", "rollout", "maximize"),
            saturn.PromotionObjective("trace_endpoints", "feedback_flags", "maximize")))

    def schedule_step():
        return attempt["step"] if schedule_on == "attempts" else cursor["updates"]

    def restore_cursor(value):
        cursor.clear()
        cursor.update(value)

    controller = saturn.DeterministicCheckpointController(
        controller_id=f"isa-direct-effect-v2-{arch}-{cfg['seed']}", model=model, optimizer=optimizer, policy=policy,
        cursor_capture=lambda: dict(cursor), cursor_restore=restore_cursor, max_interval_steps=cfg["steps"],
        receipt_store=saturn.ImmutableDirectoryReceiptStore(out / "decisions"))

    def evaluator():
        s = exactness(model, fb, rows=True)
        # with factor-grid splits the rollout programs must come from the training split too (round 5 ran without this,
        # so its rollout objective scored programs containing held cells and stayed at 0: a tie, no selection effect)
        roll = program_panel(model, device, cfg["seed"] * 10 + 3, (32,), (8,), grid=cfg.get("grid"))["32"]
        evidence = {}
        if k > 0:
            evidence = {"state_rows": saturn.pass_bits_evidence(s["rows"]["state"]),
                        "flag_rows": saturn.pass_bits_evidence(s["rows"]["flags"]),
                        "rollout_rows": saturn.pass_bits_evidence([f is None for f in roll["first_divergence"]])}
        tag = f"future-{len(observations):03d}"
        torch.save(model.state_dict(), out / "futures" / f"{tag}.pt")
        observations.append({"future": tag, "updates": cursor["updates"], "attempted": attempt["step"],
                             "lr": optimizer.param_groups[0]["lr"], "wide_large": s["wide_large_state"],
                             "feedback_state": s["state"], "feedback_flags": s["flags"], "feedback_dest_value": s["dest_value"],
                             "feedback_imm": s["imm_decode"], "rollout32": roll["exact"] / roll["programs"],
                             "per_width": s["per_width_state"], "wall_s": time.perf_counter() - t0})
        emit("ISA_DE2_FUTURE:" + json.dumps({"arch": arch, **observations[-1]}))
        model.train()
        return saturn.EvaluationScores(validation={"feedback_state": s["state"]},
            autonomous_rollout={"rollout": roll["exact"] / roll["programs"]}, trace_endpoints={"feedback_flags": s["flags"]},
            evidence={"feedback_split": "feedback (Unicorn labels)", "optimizer_split": "discovery", "labels_used": True, "future": tag,
                      **evidence})

    def update(_):
        attempt["step"] += 1
        g = torch.Generator(device="cpu").manual_seed(cfg["seed"] * 1_000_003 + attempt["interval"] * 1_000_000 + attempt["step"])
        idx = torch.randint(0, n, (cfg["batch"],), generator=g).to(device)
        lr = lr_at(schedule_step() - (1 if schedule_on == "attempts" else 0), cfg["lr"], warmup, total)
        for group in optimizer.param_groups:  # set inside the update → the accepted snapshot always matches live state
            group["lr"] = lr
        t = batch(d, idx)
        optimizer.zero_grad(set_to_none=True)
        total_loss = loss_fn(model(t["win"], t["regs"], t["flags"]), t)
        total_loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        cursor["updates"] += 1
        return {"loss": float(total_loss.detach()), "lr": lr, "attempt": attempt["step"]}

    model.train()
    controller.establish_baseline(evaluator)
    best, stale, accepted = -1.0, 0, []
    interval = 0
    while schedule_step() < total and attempt["step"] < cfg["max_attempt_steps"]:
        attempt["interval"] = interval
        before = cursor["updates"]
        controller.run_interval(interval_id=f"interval-{interval:03d}", steps=cfg["steps"], train_step=update, evaluator=evaluator)
        accepted.append(cursor["updates"] > before)
        observations[-1]["accepted"] = accepted[-1]
        observations[-1]["relation"] = controller.ledger.receipts[-1].to_dict()["decision"]["reason"]
        score = observations[-1]["feedback_state"]
        if accepted[-1] and score > best + cfg["plateau_delta"]:
            best, stale = score, 0
        else:
            stale += 1
        interval += 1
        if stale >= cfg["patience"]:
            emit("ISA_DE2_PLATEAU:" + json.dumps({"arch": arch, "updates": cursor["updates"], "best": best}))
            break
    model.eval()
    torch.save(model.state_dict(), out / "model.pt")
    return model, {"trajectory": observations, "train_wall_s": time.perf_counter() - t0, "accepted_updates": cursor["updates"],
                   "attempted_updates": attempt["step"], "parameters": sum(p.numel() for p in model.parameters()),
                   "rollback_receipts": [r.to_dict() for r in controller.ledger.receipts]}


def replay(arch, out, device, panels, probe, emit=print, aligned=False, relptr=False, regptr=False, extra=None,
           fieldptr=False, maskkey=False, aux_detach=None):
    """Restore every retained future and measure exactness and probes along the training trajectory."""
    out = Path(out)
    rows = []
    for path in sorted((out / "futures").glob("future-*.pt")):
        model = Executor(arch, store=True, aligned=aligned, relptr=relptr, regptr=regptr, fieldptr=fieldptr, maskkey=maskkey,
                         aux_detach=aux_detach).to(device)
        model.load_state_dict(torch.load(path, map_location=device))
        model.eval()
        iid, held = exactness(model, panels["iid"]), exactness(model, panels["heldout_literal"])
        row = {"future": path.stem, "iid": iid["state"], "heldout_literal": held["state"],
               "iid_wide_large": iid["wide_large_state"], "heldout_wide_large": held["wide_large_state"],
               **{f"{k}_{f}": e[g] for k, e in ((k, exactness(model, v)) for k, v in (extra or {}).items())
                  for f, g in (("state", "state"), ("per_form", "per_form_state"))},
               "probes": probe_panel(model, probe, device)}
        rows.append(row)
        emit("ISA_DE2_REPLAY:" + json.dumps({"arch": arch, "future": row["future"], "iid": round(row["iid"], 4),
             "carry_last": row["probes"].get("carry_in", {}).get(f"layer{len(model.mixers) - 1}")}))
    return rows


@torch.no_grad()
def carry_run_panel(model, device, seed, per_length=16):
    """`ADD RDI, 1` (48 83 C7 01) on RDI whose low L bits are all ones (carry ripples L places), L = 0..63."""
    rng, emu = random.Random(seed), Emulator()
    ins = encode("add_r64_8", 7, 1)
    examples = []
    for length in range(64):
        for _ in range(per_length):
            state = P.random_state(rng)
            high = rng.getrandbits(64) & ~((1 << (length + 1)) - 1) & MASK64
            state["regs"][7] = high | ((1 << length) - 1)  # bit L is 0, so the carry stops exactly there
            examples.append(make_example(rng, emu, ins, state))
    d = to_device(pack(examples), device)
    model.eval()
    oks = []
    for start in range(0, len(examples), 256):  # chunked like exactness(): one 1024-row batch spiked Hydra past its VRAM lease
        t = batch(d, torch.arange(start, min(len(examples), start + 256), device=device))
        out = model(t["win"], t["regs"], t["flags"])
        oks.append(((out["regs"] > 0).float() == t["after"]).all(-1).all(-1) & ((out["flags"] > 0).float() == t["after_flags"]).all(-1))
    ok = torch.cat(oks).view(64, per_length)
    rates = ok.float().mean(1).cpu().tolist()
    return {"per_run_length": [round(r, 4) for r in rates], "first_length_below_1": next((i for i, r in enumerate(rates) if r < 1), None)}
