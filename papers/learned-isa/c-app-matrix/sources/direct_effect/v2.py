"""x86-de64-v2: literal-diverse direct-effect training, stores/syscalls, plateau-stopped Saturn runs, probe replay.

Changes from v1 (reported):
- Immediates cover every residue. The sealed heldout is a set of 24 literal VALUES for the immediate's low
  byte (never 0, 1, 8 or 60, which the counter/stdout programs use), plus seven (form, register) pairs.
- More encodings per family: no-REX `C7 /0` (MOV r/m32, imm32), reg-reg MOV (`89`, `48 89`, `48 8B`), `48 31`
  XOR, and `MOV [RSP], r64` (`48 89 /r` with SIB 0x24) whose memory store the model emits (enable, address,
  value). With stores and the OS boundary (write/exit after the model emits SYSCALL) the stdout ELFs run.
- Data are compact integer arrays generated by parallel Unicorn workers; bits are expanded on the device.
- Learning rate: warmup then cosine, computed inside each update from the restored update counter, so live
  optimizer state always equals the accepted checkpoint (no Saturn drift). Batches are drawn per interval
  attempt, so a rejected future is followed by fresh data rather than an identical replay.
- Every future's weights are kept; afterwards each one is replayed for exactness and Rosetta probes.
"""
